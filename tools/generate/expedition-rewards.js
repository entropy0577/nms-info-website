// Generates src/lib/data/expedition-rewards.yaml: frigate expedition reward pools from the game's EXPEDITIONREWARDTABLE
// (game version 3.10, unmodded EXML extract in the csakypeter/NMS-BetterRewards GitHub repository), with item ids
// turned into names using the community wiki's "Item Id List" page (CC BY-SA). Ids missing from that page are named in
// tools/generate/corrections/expedition-rewards.yaml (itemNames).
//
// Usage: node tools/generate/expedition-rewards.js [--check] [--refresh]
import { fetchText, wikitext } from './lib/wiki.js';
import { loadCorrections } from './lib/corrections.js';
import { writeData } from './lib/output.js';

// Pinned to a commit so the source can't change underneath us.
const EXML = 'https://raw.githubusercontent.com/csakypeter/NMS-BetterRewards/e7eec1e9b0dee16a57f78a377b9bfd048fab11b5/Current/EXMLs/EXPEDITIONREWARDTABLE.EXML';

// Reward table ids are R_<TYPE>_<n> (normal) and R_<TYPE>_EASY_<n> (small fleets), each type with its own spelling.
const TYPES = {
  Trade: { normal: 'DIPLOMATIC', small: 'DIP_EASY' },
  Combat: { normal: 'COMBAT', small: 'COM_EASY' },
  Exploration: { normal: 'EXPLORATION', small: 'EXP_EASY' },
  Industrial: { normal: 'MINING', small: 'MINE_EASY' },
};

const settings = loadCorrections('expedition-rewards');
if (settings.corrections.length) throw new Error('expedition-rewards takes no record corrections — only itemNames.');

// Item Id List rows look like: |TRA_CURIO1||[[File:…|50px]]||[[Gek Relic]]||product
const names = new Map(
  [...(await wikitext('Item Id List')).matchAll(/^\|([A-Z0-9_]+)\|\|.*?\|\|\[\[([^\]|]+)(?:\|[^\]]*)?\]\]\|\|/gm)].map((m) => [m[1], m[2]]),
);
for (const [id, name] of Object.entries(settings.itemNames || {})) {
  if (names.has(id)) throw new Error(`itemNames.${id} is now on the wiki's Item Id List (as "${names.get(id)}") — remove it from the corrections file.`);
  names.set(id, name);
}

// EXML is a tree of <Property name="…" value="…"> elements. Each table entry is a GcGenericRewardTableEntry with an Id
// and a list of GcRewardTableItem rewards; within an item the first Id / AmountMin / AmountMax / Currency belong to it.
const prop = (xml, name) => xml.match(new RegExp(`<Property name="${name}" value="([^"]*)"`))?.[1];

function reward(xml) {
  const type = prop(xml, 'Reward');
  const chance = Number(prop(xml, 'PercentageChance'));
  const amount = { min: Number(prop(xml, 'AmountMin')), max: Number(prop(xml, 'AmountMax')) };
  switch (type) {
    case 'GcRewardMoney.xml':
      // <Property name="Currency" value="GcCurrency.xml"> wraps <Property name="Currency" value="Units" />.
      return { item: xml.match(/name="Currency" value="(\w+)" \/>/)[1], chance, ...amount };
    case 'GcRewardSpecificProduct.xml':
    case 'GcRewardSpecificSubstance.xml': {
      const id = prop(xml, 'Id');
      if (!names.has(id)) throw new Error(`No name for item id ${id} — add it to itemNames in the corrections file.`);
      return { item: names.get(id), chance, ...amount };
    }
    case 'GcRewardProceduralProduct.xml': // a random artifact of a category (Plant, BioSample, …); no amount
      return { item: 'Random artifact / curiosity', chance, min: null, max: null };
    default:
      throw new Error(`Unknown reward type ${type}`);
  }
}

const tables = new Map(
  (await fetchText(EXML))
    .split('<Property value="GcGenericRewardTableEntry.xml">')
    .slice(1)
    .map((entry) => [prop(entry, 'Id'), entry.split('<Property value="GcRewardTableItem.xml">').slice(1).map(reward)]),
);

/** The pools R_<code>_0, _1, … in order. */
function pools(code) {
  const out = [];
  for (let i = 0; tables.has(`R_${code}_${i}`); i++) out.push(tables.get(`R_${code}_${i}`));
  if (!out.length) throw new Error(`No reward tables R_${code}_n`);
  return out;
}

const expeditionRewards = Object.fromEntries(
  Object.entries(TYPES).map(([type, codes]) => [type, { normal: pools(codes.normal), small: pools(codes.small) }]),
);

writeData(
  'expedition-rewards',
  [
    "Frigate expedition reward pools, from the game's EXPEDITIONREWARDTABLE (game version 3.10, unmodded extract published in the",
    "csakypeter/NMS-BetterRewards repository). Its contents match the community wiki's loot summary (from the 3.75 files).",
    "Generated by tools/generate/expedition-rewards.js; item names from the No Man's Sky community wiki's Item Id List (CC BY-SA),",
    'Nov 2026, plus itemNames in tools/generate/corrections/expedition-rewards.yaml.',
    'Each expedition type has several reward pools; "small" pools appear to be used for small fleets (1–3 frigates).',
    'chance = % chance that item is included when that pool pays out; min/max = amount.',
  ],
  { expeditionRewards },
);
