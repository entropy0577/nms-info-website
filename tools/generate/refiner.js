// Generates src/lib/data/refiner.yaml from the No Man's Sky community wiki (nomanssky.fandom.com, CC BY-SA).
//
// Which pages: every item page that uses the {{PoC-Refine|…}} template (it lists the recipes that PRODUCE that item).
//
// Order: the data was first extracted from the resources in the "Elements" table of the wiki's "Resource" page plus a
// few product pages (`extraPages` in corrections/refiner.yaml), requested 26 titles at a time; the MediaWiki API returns
// each batch in page-ID order. That order is kept (items grouped per batch, by page ID; recipes in page order), and the
// remaining PoC-Refine pages follow alphabetically, so a page newly added to the wiki only appends to the diff.
//
// Usage: node tools/generate/refiner.js [--check] [--refresh]
import { wikitext, wikitextMany, fetchText } from './lib/wiki.js';
import { loadCorrections, applyCorrections } from './lib/corrections.js';
import { writeData } from './lib/output.js';

const API = 'https://nomanssky.fandom.com/api.php';
const BATCH = 26;

/** Item names from the Elements table: rows look like `|[[File:X.png|50px]]||[[Carbon]]||C||Organic||…`. */
function elementNames(resourcePage) {
  const section = resourcePage.split(/^==\s*Elements\s*==\s*$/m)[1].split(/^\|\}/m)[0];
  return [...section.matchAll(/^\|\[\[File:[^\]]*\]\]\s*\|\|\s*\[\[([^\]|]+)/gm)].map((m) => m[1].trim());
}

/** Page IDs for titles (redirects followed): Map title → { title: final title, id }. */
async function pageIds(titles) {
  const url = `${API}?action=query&redirects=1&format=json&formatversion=2&titles=${encodeURIComponent(titles.join('|'))}`;
  const q = JSON.parse(await fetchText(url)).query;
  const final = (t) => {
    const n = q.normalized?.find((x) => x.from === t)?.to ?? t;
    return q.redirects?.find((x) => x.from === n)?.to ?? n;
  };
  const ids = new Map(q.pages.filter((p) => !p.missing).map((p) => [p.title, p.pageid]));
  return new Map(titles.map((t) => [t, { title: final(t), id: ids.get(final(t)) }]));
}

/**
 * Recipes from the {{PoC-Refine}} templates of one item page. Each template argument is one recipe:
 *   `<ingredient>,<amount>;[…;]<output qty>;<seconds per unit>[%<process name>]`
 * Ingredient names may contain commas, so the amount is split off at the last comma.
 */
function parseRefine(item, text) {
  const out = [];
  text = text.replace(/<!--[\s\S]*?-->/g, '');
  for (const m of text.matchAll(/\{\{\s*PoC-Refine\s*\|([^}]*)\}\}/g)) {
    for (let arg of m[1].split('|')) {
      arg = arg.trim().replace(/^\d+\s*=\s*/, '');
      if (!arg) continue;
      const [parts, name] = arg.split('%');
      const fields = parts.split(';').map((s) => s.trim());
      const qty = Number(fields.at(-2));
      const inputs = fields.slice(0, -2).map((f) => {
        const i = f.lastIndexOf(',');
        return [f.slice(0, i).trim(), Number(f.slice(i + 1))];
      });
      if (!inputs.length || inputs.some(([n, a]) => !n || !Number.isFinite(a)) || !Number.isFinite(qty))
        throw new Error(`${item}: can't parse PoC-Refine recipe "${arg}"`);
      out.push({ out: item, qty, in: inputs, name: name?.trim() || null });
    }
  }
  return out;
}

/** Every main-namespace page that uses Template:PoC-Refine. */
async function refinePages() {
  const titles = [];
  let cont = '';
  do {
    const url = `${API}?action=query&list=embeddedin&eititle=Template:PoC-Refine&einamespace=0&eilimit=500&format=json&formatversion=2${cont}`;
    const json = JSON.parse(await fetchText(url));
    titles.push(...json.query.embeddedin.map((p) => p.title));
    cont = json.continue ? `&eicontinue=${encodeURIComponent(json.continue.eicontinue)}` : '';
  } while (cont);
  return titles;
}

const { corrections, extraPages = [] } = loadCorrections('refiner');
const ordered = [...elementNames(await wikitext('Resource')), ...extraPages];
const rest = (await refinePages()).filter((t) => !ordered.includes(t)).sort();

const records = [];
// Original order: batches of 26 titles, each in page-ID order.
for (let i = 0; i < ordered.length; i += BATCH) {
  const batch = [...(await pageIds(ordered.slice(i, i + BATCH))).values()].filter((p) => p.id).sort((a, b) => a.id - b.id);
  const texts = await wikitextMany(batch.map((p) => p.title));
  for (const p of batch) records.push(...parseRefine(p.title, texts.get(p.title)));
}
// Every other page with a PoC-Refine template, alphabetically.
const restTexts = await wikitextMany(rest);
for (const t of rest) records.push(...parseRefine(t, restTexts.get(t)));

writeData(
  'refiner',
  [
    `Refiner recipes from the No Man's Sky community wiki (nomanssky.fandom.com, CC BY-SA): the PoC-Refine templates on the`,
    `item pages (every page using that template). Generated by tools/generate/refiner.js, November 2026;`,
    `ordering settings and any hand corrections are in tools/generate/corrections/refiner.yaml.`,
    `out = product, qty = output amount, in = [[input, amount], ...], name = in-game process name.`,
  ],
  { refinerRecipes: applyCorrections(records, corrections) },
);
